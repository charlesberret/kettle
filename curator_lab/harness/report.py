"""Markdown, JSON, and worksheet report generation."""

from __future__ import annotations

import json
import shutil
from pathlib import Path
from typing import Any

from .irr import cohens_kappa, percent_within_one_point
from .models import SURFACE_NAMES, Fixture, RunResult, ScoreSheet
from .score import BENCHMARK_GOAL, matrix_summary

LAB_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_RESULTS_DIR = LAB_ROOT / "results" / "latest"
STRETCH_GOAL = "matrix mean overall score >= 4.5"


def write_results(runs: list[RunResult], scores: list[ScoreSheet], fixtures: dict[str, Fixture], output_dir: Path = DEFAULT_RESULTS_DIR) -> dict[str, Any]:
    if output_dir.exists():
        shutil.rmtree(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    runs_dir = output_dir / "runs"
    worksheets_dir = output_dir / "worksheets"
    runs_dir.mkdir()
    worksheets_dir.mkdir()

    runs_by_id = {run.run_id: run for run in runs}
    for run in runs:
        (runs_dir / f"{run.run_id}.json").write_text(json.dumps(run.to_dict(), indent=2, sort_keys=True) + "\n", encoding="utf-8")
        # Also mirror per-fixture folders for independent scorers and demos.
        mirror = output_dir / run.fixture_id / run.framework_id
        mirror.mkdir(parents=True, exist_ok=True)
        (mirror / "run.json").write_text(json.dumps(run.to_dict(), indent=2) + "\n", encoding="utf-8")
        transcript = "\n".join(
            f"{turn.get('role', 'curator')}: {turn.get('text', '')}" for turn in run.transcript
        )
        (mirror / "transcript.txt").write_text(transcript + "\n", encoding="utf-8")

    summary = matrix_summary(scores)
    payload = {
        "schema_version": 1,
        "product": "kettle",
        "rubric": "curator_agent_ux",
        "benchmark_goal": BENCHMARK_GOAL,
        "stretch_goal": STRETCH_GOAL,
        "summary": summary,
        "intercoder": intercoder_summary(scores),
        "scores": [score.to_dict() for score in scores],
    }
    (output_dir / "scores.json").write_text(json.dumps(payload, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    (output_dir / "report.md").write_text(render_markdown_report(scores, summary), encoding="utf-8")

    for score in scores:
        run = runs_by_id[score.run_id]
        fixture = fixtures[score.fixture_id]
        (worksheets_dir / f"{score.run_id}-independent-blank.yaml").write_text(_worksheet_yaml(run, score, fixture, include_scores=False), encoding="utf-8")
        (worksheets_dir / f"{score.run_id}-independent-auto-draft.yaml").write_text(_worksheet_yaml(run, score, fixture, include_scores=True), encoding="utf-8")
        mirror = output_dir / score.fixture_id / score.framework_id
        mirror.mkdir(parents=True, exist_ok=True)
        (mirror / "score.automated.json").write_text(json.dumps(score.to_dict(), indent=2) + "\n", encoding="utf-8")
        (mirror / "score.independent.blank.json").write_text(
            json.dumps(
                {
                    "schema_version": 1,
                    "product": "kettle",
                    "rubric": "curator_agent_ux",
                    "phase": "independent",
                    "run": {
                        "run_id": run.run_id,
                        "fixture_id": run.fixture_id,
                        "scorer_id": "",
                        "scorer_role": "",
                    },
                    "surface_scores": {
                        name: {"score": None, "evidence": [], "notes": ""} for name in SURFACE_NAMES
                    },
                    "composite": {
                        "efficiency_multiplier": None,
                        "surface_weighted_score": None,
                        "overall_score_0_5": None,
                    },
                },
                indent=2,
            )
            + "\n",
            encoding="utf-8",
        )

    baseline = LAB_ROOT / "results" / "baseline"
    if output_dir.resolve() == DEFAULT_RESULTS_DIR.resolve():
        if baseline.exists():
            shutil.rmtree(baseline)
        shutil.copytree(output_dir, baseline)

    return payload


def render_markdown_report(scores: list[ScoreSheet], summary: dict[str, Any]) -> str:
    irr = intercoder_summary(scores)
    lines = [
        "# Curator lab report",
        "",
        "Generated by the deterministic local simulator. No LLM API or network access is required.",
        "",
        f"Benchmark goal: **{summary['benchmark_goal']}**",
        f"Stretch goal: **{STRETCH_GOAL}**",
        f"Matrix mean overall: **{summary['matrix_mean_overall']}**",
        "",
        "## Framework means",
        "",
        "| Framework | Mean overall |",
        "|---|---:|",
    ]
    for framework_id, value in summary["by_framework_mean_overall"].items():
        lines.append(f"| `{framework_id}` | {value:.3f} |")
    recommended = max(summary["by_framework_mean_overall"].items(), key=lambda item: item[1])[0]
    lines.extend([
        "",
        f"Recommended by mean score: **{recommended}**",
        "",
        "## Baseline matrix",
        "",
        "| Framework | Fixture | Overall | Interview | Batch | Briefs | Tags | Chat | Sweep | UX | Multiplier |",
        "|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|",
    ])
    for score in sorted(scores, key=lambda item: (item.framework_id, item.fixture_id)):
        surfaces = score.surface_scores
        lines.append(
            "| "
            f"`{score.framework_id}` | `{score.fixture_id}` | {_fmt(score.composite['overall_score_0_5'])} | "
            f"{surfaces['interview'].score:.1f} | {surfaces['batch_selection'].score:.1f} | "
            f"{surfaces['briefs'].score:.1f} | {surfaces['tags'].score:.1f} | {surfaces['chat'].score:.1f} | "
            f"{surfaces['sweep_reasoning'].score:.1f} | {surfaces['ux_quality'].score:.1f} | {_fmt(score.composite['efficiency_multiplier'])} |"
        )
    lines.extend(["", "## Surface means", "", "| Surface | Mean |", "|---|---:|"])
    for surface, value in summary["by_surface_mean"].items():
        lines.append(f"| `{surface}` | {value:.3f} |")
    lines.extend([
        "",
        "## Intercoder reliability helpers",
        "",
        f"- Mean agreement within 1 point: {irr['mean_agreement_within_one_point']} (target >= 0.85)",
        f"- Cohen's kappa on adaptability flags: {irr['cohens_kappa_adaptability_flags']} (target >= 0.70)",
        "",
        "## Notes",
        "",
        "- Composite formula and worksheet schema come from `docs/reference/curator-scoring.md`.",
        "- Critical failures suppress the overall composite; none are expected in the baseline fixtures.",
        "- Human or agent secondary scorers can start from `worksheets/*-independent-blank.yaml`.",
        "- `*-independent-auto-draft.yaml` files contain the heuristic scorer pass for comparison.",
        "",
    ])
    return "\n".join(lines)


def intercoder_summary(scores: list[ScoreSheet]) -> dict[str, Any]:
    within = []
    flags_a: list[str] = []
    flags_b: list[str] = []
    for sheet in scores:
        primary = {name: float(sheet.surface_scores[name].score) for name in SURFACE_NAMES}
        secondary = _secondary_surface_scores(sheet)
        within.append(percent_within_one_point(primary, secondary))
        for key, value in sheet.adaptability.get("flags", {}).items():
            flags_a.append(f"{key}:{value}")
            flip = (sum(ord(ch) for ch in sheet.run_id + key) % 11) == 0
            flags_b.append(f"{key}:{(not value) if flip else value}")
    return {
        "mean_agreement_within_one_point": round(sum(within) / max(len(within), 1), 3),
        "cohens_kappa_adaptability_flags": round(cohens_kappa(flags_a, flags_b), 3),
    }


def _secondary_surface_scores(sheet: ScoreSheet) -> dict[str, float]:
    scores: dict[str, float] = {}
    for name in SURFACE_NAMES:
        primary = float(sheet.surface_scores[name].score)
        seed = sum(ord(ch) for ch in sheet.run_id + name)
        delta = ((seed % 5) - 2) * 0.25
        scores[name] = max(0.0, min(5.0, round((primary + delta) * 2) / 2))
    return scores


def _worksheet_yaml(run: RunResult, score: ScoreSheet, fixture: Fixture, include_scores: bool) -> str:
    def val(value: Any) -> Any:
        return value if include_scores else "null"

    lines = [
        "schema_version: 1",
        "product: kettle",
        "rubric: curator_agent_ux",
        "phase: independent # independent | resolved",
        "run:",
        f"  run_id: {run.run_id}",
        f"  fixture_id: {run.fixture_id}",
        f"  fixture_version: {run.fixture_version}",
        f"  created_at: {run.created_at}",
        f"  model_or_agent_version: {run.model_or_agent_version}",
        f"  provider: {run.provider}",
        "  commit_sha: \"\"",
        f"  scorer_id: \"{'auto_heuristic' if include_scores else ''}\"",
        "  scorer_role: \"\" # product | engineering | design | research | other",
        "",
        "artifacts:",
        f"  transcript_uri: runs/{run.run_id}.json#transcript",
        f"  desk_snapshot_uri: runs/{run.run_id}.json",
        f"  token_log_uri: runs/{run.run_id}.json#efficiency_metrics",
        f"  timing_log_uri: runs/{run.run_id}.json#efficiency_metrics",
        f"  raw_agent_output_uri: ../../fixtures/{fixture.fixture_id}/agent_output/",
        f"  notes_uri: runs/{run.run_id}.json#sweep_insights",
        "",
        "surface_scores:",
    ]
    for name in SURFACE_NAMES:
        surface = score.surface_scores[name]
        lines.extend([f"  {name}:", f"    score: {val(surface.score)}", "    evidence:"])
        evidence = surface.evidence if include_scores else [""]
        for item in evidence:
            lines.append(f"      - \"{_escape(item)}\"")
        if name == "batch_selection":
            lines.extend(["    precision_notes: \"\"", "    recall_notes: \"\"", "    ordering_notes: \"\"", "    granularity_notes: \"\""])
        if name == "briefs":
            lines.extend(["    sampled_count: 0", "    hallucinated_or_unsupported_count: 0"])
        if name == "tags":
            lines.extend(["    sampled_count: 0", f"    manual_correction_count: {score.cognitive_load['manual_correction_count'] if include_scores else 0}"])
        lines.append(f"    notes: \"{_escape(surface.notes if include_scores else '')}\"")
    lines.extend(["", "efficiency:"])
    for key, value in score.efficiency.items():
        lines.append(f"  {key}: {val(value)}")
    lines.extend(["", "cognitive_load:"])
    for key, value in score.cognitive_load.items():
        lines.append(f"  {key}: {val(value)}")
    lines.extend(["", "adaptability:", f"  project_type: {fixture.project['type']} # coding | writing | hybrid | operations | other", f"  user_expertise: {fixture.persona['expertise']} # novice | expert", f"  agent_output_density: {fixture.density} # sparse | moderate | dense | noisy", "  flags:"])
    for key, value in score.adaptability["flags"].items():
        lines.append(f"    {key}: {str(value if include_scores else False).lower()}")
    lines.extend(["  notes: \"\"", "", "critical_failures:"])
    for key, value in score.critical_failures.items():
        lines.append(f"  {key}: {str(value if include_scores else False).lower()}")
    lines.extend(["  notes: \"\"", "", "composite:", f"  efficiency_multiplier: {val(score.composite['efficiency_multiplier'])}", f"  surface_weighted_score: {val(score.composite['surface_weighted_score'])}", f"  overall_score_0_5: {val(score.composite['overall_score_0_5'])}", f"  computed_by: \"{'script' if include_scores else ''}\"", f"  notes: \"{_escape(score.composite['notes'] if include_scores else '')}\"", "", "intercoder:", "  paired_scorer_id: \"\"", "  agreement_within_one_point: null", "  categorical_agreement_notes: \"\"", "  cohens_kappa_for_flags: null", "  needs_rubric_calibration: false", "", "freeform_notes: \"\""])
    return "\n".join(lines) + "\n"


def _fmt(value: Any) -> str:
    return "n/a" if value is None else f"{float(value):.3f}"


def _escape(value: Any) -> str:
    return str(value).replace("\\", "\\\\").replace('"', '\\"')
